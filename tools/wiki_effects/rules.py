# ---- 備考（全文）の整形 ----

def clean_note_line(line):
    """Wiki ページ内の別の場所を指す記述を除く（アプリ内では意味がないため）"""
    line = line.replace('(下記参照)', '').replace('（下記参照）', '')
    line = line.replace('ため表下部「検証結果（近接攻撃力上昇）」や', 'ため、Wikiの検証結果や')
    line = line.replace('詳細は検証結果に記載。', '')
    if line.endswith('仮説については下部を参照'):
        line = line[:-len('仮説については下部を参照')].rstrip('。')
    if line in ('下部を参照', '詳細については下部を参照'):
        return ''
    return line.strip()


